#!/usr/bin/env python3
"""Generate and deterministically check host-specific Skill adapters."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

import yaml

try:
    from validation_utils import non_empty_string
except ImportError:  # pragma: no cover - used when imported as scripts.sync_adapters
    from .validation_utils import non_empty_string

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_MANIFEST = ROOT / "adapters" / "manifest.yaml"
SCHEMA_VERSION = 1
SKILL_NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
HEX_COLOR_RE = re.compile(r"^#[0-9A-Fa-f]{6}$")
GENERATED_YAML_HEADER = "# Generated by scripts/sync_adapters.py from adapters/manifest.yaml. Do not hand-edit.\n"


def within_root(path: Path, root: Path) -> bool:
    try:
        path.resolve().relative_to(root.resolve())
        return True
    except ValueError:
        return False


def is_safe_relative_path(value: Any) -> bool:
    if not non_empty_string(value):
        return False
    if "\\" in value or value.startswith("/") or re.match(r"^[A-Za-z]:", value):
        return False
    parts = value.split("/")
    return not any(part in ("", ".", "..") for part in parts)


def load_manifest(path: Path) -> tuple[dict[str, Any] | None, list[str]]:
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError) as exc:
        return None, [f"{path}: invalid adapter manifest: {exc}"]

    if not isinstance(data, dict):
        return None, [f"{path}: adapter manifest must be a mapping"]

    errors: list[str] = []
    if data.get("schema_version") != SCHEMA_VERSION:
        errors.append(f"{path}: schema_version must equal {SCHEMA_VERSION}")

    plugin = data.get("plugin")
    if not isinstance(plugin, dict):
        errors.append(f"{path}: plugin metadata mapping is required")
    else:
        for field in ("name", "version", "description", "license", "repository"):
            if not non_empty_string(plugin.get(field)):
                errors.append(f"{path}: plugin.{field} must be a non-empty string")
        if non_empty_string(plugin.get("name")) and not SKILL_NAME_RE.fullmatch(plugin["name"]):
            errors.append(f"{path}: plugin.name must be kebab-case")

    adapters = data.get("adapters")
    if not isinstance(adapters, dict) or not adapters:
        errors.append(f"{path}: adapters must be a non-empty mapping")
    else:
        unknown = sorted(set(adapters) - {"codex", "claude_code"})
        if unknown:
            errors.append(f"{path}: unsupported adapter key(s): {', '.join(unknown)}")

    return (None, errors) if errors else (data, [])


def render_openai_yaml(config: dict[str, Any]) -> bytes:
    interface: dict[str, str] = {
        "display_name": config["display_name"],
        "short_description": config["short_description"],
    }
    if non_empty_string(config.get("default_prompt")):
        interface["default_prompt"] = config["default_prompt"]
    if non_empty_string(config.get("brand_color")):
        interface["brand_color"] = config["brand_color"]

    payload = {
        "interface": interface,
        "policy": {
            "allow_implicit_invocation": bool(config.get("allow_implicit_invocation", True)),
        },
    }
    rendered = GENERATED_YAML_HEADER + yaml.safe_dump(payload, sort_keys=False, allow_unicode=True)
    return rendered.encode("utf-8")


def render_codex_plugin_json(plugin: dict[str, Any], skills_dir: str) -> bytes:
    payload = {
        "name": plugin["name"],
        "version": plugin["version"],
        "description": plugin["description"],
        "license": plugin["license"],
        "repository": plugin["repository"],
        "skills": f"./{skills_dir}",
    }
    return (json.dumps(payload, indent=2) + "\n").encode("utf-8")


def render_claude_plugin_json(plugin: dict[str, Any]) -> bytes:
    payload = {
        "name": plugin["name"],
        "version": plugin["version"],
        "description": plugin["description"],
        "license": plugin["license"],
        "repository": plugin["repository"],
    }
    return (json.dumps(payload, indent=2) + "\n").encode("utf-8")


def _sync_bytes(destination: Path, expected: bytes, *, check: bool, errors: list[str]) -> int:
    if check:
        if not destination.is_file():
            errors.append(f"{destination}: generated adapter file is missing")
        elif destination.read_bytes() != expected:
            errors.append(f"{destination}: generated adapter file differs from canonical source")
        return 0
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(expected)
    return 1


def _validate_adapter_paths(
    manifest: Path,
    adapter_name: str,
    cfg: dict[str, Any],
    root: Path,
) -> tuple[Path | None, Path | None, Path | None, list[str]]:
    errors: list[str] = []
    directory = cfg.get("directory")
    manifest_rel = cfg.get("manifest_path")
    skills_dir_rel = cfg.get("skills_dir", "skills")

    for field_name, val in (
        ("directory", directory),
        ("manifest_path", manifest_rel),
        ("skills_dir", skills_dir_rel),
    ):
        if not is_safe_relative_path(val):
            errors.append(f"{manifest}: adapters.{adapter_name}.{field_name} must be a safe relative POSIX path")
    if errors:
        return None, None, None, errors

    adapter_root = root / directory
    plugin_manifest = adapter_root / manifest_rel
    skills_root = adapter_root / skills_dir_rel
    for label, candidate in (
        ("directory", adapter_root),
        ("manifest_path", plugin_manifest),
        ("skills_dir", skills_root),
    ):
        if not within_root(candidate, root):
            errors.append(f"{manifest}: adapters.{adapter_name}.{label} escapes repository root")
    if errors:
        return None, None, None, errors
    return adapter_root, plugin_manifest, skills_root, []


def synchronize(root: Path, manifest: Path, check: bool) -> tuple[list[str], int]:
    data, errors = load_manifest(manifest)
    if errors or data is None:
        return errors, 0

    plugin = data["plugin"]
    adapters = data["adapters"]
    written = 0

    codex_cfg = adapters.get("codex")
    if codex_cfg is not None:
        if not isinstance(codex_cfg, dict):
            errors.append(f"{manifest}: adapters.codex must be a mapping")
        else:
            adapter_root, plugin_manifest, skills_root, path_errors = _validate_adapter_paths(
                manifest, "codex", codex_cfg, root
            )
            errors.extend(path_errors)
            skills_map = codex_cfg.get("skills")
            if not isinstance(skills_map, dict) or not skills_map:
                errors.append(f"{manifest}: adapters.codex.skills must be a non-empty mapping")
            elif adapter_root is not None and plugin_manifest is not None and skills_root is not None:
                written += _sync_bytes(
                    plugin_manifest,
                    render_codex_plugin_json(plugin, codex_cfg.get("skills_dir", "skills")),
                    check=check,
                    errors=errors,
                )

                declared = set(skills_map)
                if skills_root.exists():
                    actual = {p.parent.name for p in skills_root.glob("*/SKILL.md")}
                    for extra in sorted(actual - declared):
                        errors.append(f"{skills_root / extra / 'SKILL.md'}: undeclared Codex adapter Skill copy")

                for skill_name, skill_cfg in skills_map.items():
                    if not isinstance(skill_name, str) or not SKILL_NAME_RE.fullmatch(skill_name):
                        errors.append(f"{manifest}: invalid Codex adapter Skill name {skill_name!r}")
                        continue
                    if not isinstance(skill_cfg, dict):
                        errors.append(f"{manifest}: adapters.codex.skills.{skill_name} must be a mapping")
                        continue
                    for req_key in ("display_name", "short_description"):
                        if not non_empty_string(skill_cfg.get(req_key)):
                            errors.append(
                                f"{manifest}: adapters.codex.skills.{skill_name}.{req_key} must be a non-empty string"
                            )
                    if "allow_implicit_invocation" in skill_cfg and not isinstance(
                        skill_cfg["allow_implicit_invocation"], bool
                    ):
                        errors.append(
                            f"{manifest}: adapters.codex.skills.{skill_name}.allow_implicit_invocation must be a boolean"
                        )
                    if "brand_color" in skill_cfg and (
                        not non_empty_string(skill_cfg["brand_color"])
                        or not HEX_COLOR_RE.fullmatch(skill_cfg["brand_color"])
                    ):
                        errors.append(
                            f"{manifest}: adapters.codex.skills.{skill_name}.brand_color must be a 6-digit hex color"
                        )

                    source = root / "skills" / skill_name / "SKILL.md"
                    if not source.is_file():
                        errors.append(f"{source}: canonical Skill is missing")
                        continue
                    if any(f"adapters.codex.skills.{skill_name}." in err for err in errors):
                        continue

                    dest_skill = skills_root / skill_name / "SKILL.md"
                    dest_openai = skills_root / skill_name / "agents" / "openai.yaml"
                    written += _sync_bytes(dest_skill, source.read_bytes(), check=check, errors=errors)
                    written += _sync_bytes(dest_openai, render_openai_yaml(skill_cfg), check=check, errors=errors)

    claude_cfg = adapters.get("claude_code")
    if claude_cfg is not None:
        if not isinstance(claude_cfg, dict):
            errors.append(f"{manifest}: adapters.claude_code must be a mapping")
        else:
            adapter_root, plugin_manifest, skills_root, path_errors = _validate_adapter_paths(
                manifest, "claude_code", claude_cfg, root
            )
            errors.extend(path_errors)
            skills_list = claude_cfg.get("skills")
            if (
                not isinstance(skills_list, list)
                or not skills_list
                or any(not isinstance(name, str) or not SKILL_NAME_RE.fullmatch(name) for name in skills_list)
            ):
                errors.append(f"{manifest}: adapters.claude_code.skills must contain valid Skill names")
            elif adapter_root is not None and plugin_manifest is not None and skills_root is not None:
                written += _sync_bytes(
                    plugin_manifest,
                    render_claude_plugin_json(plugin),
                    check=check,
                    errors=errors,
                )

                declared = set(skills_list)
                if skills_root.exists():
                    actual = {p.parent.name for p in skills_root.glob("*/SKILL.md")}
                    for extra in sorted(actual - declared):
                        errors.append(f"{skills_root / extra / 'SKILL.md'}: undeclared Claude Code adapter Skill copy")

                for skill_name in skills_list:
                    source = root / "skills" / skill_name / "SKILL.md"
                    if not source.is_file():
                        errors.append(f"{source}: canonical Skill is missing")
                        continue
                    dest_skill = skills_root / skill_name / "SKILL.md"
                    written += _sync_bytes(dest_skill, source.read_bytes(), check=check, errors=errors)

    return errors, written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate or deterministically check host-specific Skill adapters.",
    )
    parser.add_argument("--check", action="store_true", help="Fail if generated adapters drift from canonical sources.")
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST, help="Path to adapters/manifest.yaml.")
    args = parser.parse_args(argv)

    errors, written = synchronize(ROOT, args.manifest.resolve(), args.check)
    if errors:
        print("Adapter synchronization failed:")
        for error in errors:
            print(f"- {error}")
        return 1

    if args.check:
        print("Host adapter packages match canonical Skills and adapters/manifest.yaml.")
    else:
        print(f"Synchronized {written} host adapter files.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
